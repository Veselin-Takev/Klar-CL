let zeilen = readFileSync('server.ts', 'utf8').split('\n');
let geaendert = 0;

for (const [name, neu] of Object.entries(BLOECKE)) {
  const [anfang, ende] = ANKER[name];
  const i = zeilen.findIndex(z => z.includes(anfang));
  if (i < 0) { console.error(`ABBRUCH: ${name} nicht gefunden.`); process.exit(1); }
  let j = -1;
  for (let k = i + 1; k < zeilen.length; k++) { if (zeilen[k] === ende) { j = k; break; } }
  if (j < 0) { console.error(`ABBRUCH: Blockende von ${name} nicht gefunden.`); process.exit(1); }

  if (zeilen.slice(i, j + 1).join('\n') === neu.join('\n')) {
    console.log(`${name}: schon aktuell.`);
  } else {
    zeilen.splice(i, j - i + 1, ...neu);
    console.log(`${name}: ersetzt (${j - i + 1} -> ${neu.length} Zeilen).`);
    geaendert++;
  }
}
if (geaendert) writeFileSync('server.ts', zeilen.join('\n'));

